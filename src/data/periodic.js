/**
 * 원자번호로 주기율표의 자리(주기·족)를 구한다.
 *
 * 주기율표는 원자번호 순으로 채워지므로 번호만으로 자리가 나온다.
 * 다만 두 군데가 예외다.
 *   - 2·3주기는 8칸뿐이라 1·2족 다음 13족으로 건너뛴다 (가운데 d 자리가 없다)
 *   - 란타넘족(57~71)·악티늄족(89~103)은 표 아래 두 줄로 뺀다. 실제 주기율표도
 *     그렇게 그린다 — 안 그러면 표가 가로로 너무 길어진다
 */
export function tableSlot(z) {
  // 란타넘족·악티늄족은 아래 별도 두 줄로
  if (z >= 57 && z <= 71) return { period: 9, group: z - 57 + 4 };
  if (z >= 89 && z <= 103) return { period: 10, group: z - 89 + 4 };

  const ROWS = [
    { start: 1, period: 1 },
    { start: 3, period: 2 },
    { start: 11, period: 3 },
    { start: 19, period: 4 },
    { start: 37, period: 5 },
    { start: 55, period: 6 },
    { start: 87, period: 7 },
  ];
  const ENDS = [2, 10, 18, 36, 54, 86, 118];

  const idx = ENDS.findIndex((e) => z <= e);
  if (idx < 0) return { period: 7, group: 18 };
  const { start, period } = ROWS[idx];

  if (period === 1) return { period, group: z === 1 ? 1 : 18 };

  let offset = z - start;
  if (period === 2 || period === 3) {
    // 8칸 줄 — 1,2족 다음은 13족부터
    return { period, group: offset < 2 ? offset + 1 : offset + 11 };
  }
  // 6·7주기는 f블록 15개를 아래로 뺐으므로 그만큼 당긴다
  if (period === 6 && z > 71) offset -= 14;
  if (period === 7 && z > 103) offset -= 14;
  return { period, group: Math.min(18, offset + 1) };
}
